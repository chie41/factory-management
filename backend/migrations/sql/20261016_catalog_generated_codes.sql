BEGIN;
CREATE SEQUENCE IF NOT EXISTS design_model_code_seq;
CREATE SEQUENCE IF NOT EXISTS component_code_seq;
SELECT setval('design_model_code_seq',GREATEST(1,COALESCE((SELECT max(substring(code FROM 3)::bigint) FROM design_models WHERE code ~ '^MM[0-9]{1,18}$'),0)+1),false);
SELECT setval('component_code_seq',GREATEST(1,COALESCE((SELECT max(substring(code FROM 3)::bigint) FROM components WHERE code ~ '^CK[0-9]{1,18}$'),0)+1),false);
CREATE OR REPLACE FUNCTION catalog_code_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.code IS DISTINCT FROM OLD.code THEN
  RAISE EXCEPTION 'Catalog codes are generated by the backend and cannot be changed' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER design_model_code_immutable BEFORE UPDATE OF code ON design_models FOR EACH ROW EXECUTE FUNCTION catalog_code_immutable();
CREATE TRIGGER component_code_immutable BEFORE UPDATE OF code ON components FOR EACH ROW EXECUTE FUNCTION catalog_code_immutable();
COMMIT;
